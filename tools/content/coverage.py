"""How much of what the app asks can be signed; unsigned words go to tools/ml/target_words.txt.
The word lists mirror TextSigning.kt: keep them in step."""
import json
import pathlib
import re
import sys
import collections

ROOT = pathlib.Path(__file__).resolve().parents[2]
ASSETS = ROOT / "app" / "src" / "main" / "assets" / "content"
TARGETS = ROOT / "tools" / "ml" / "target_words.txt"

# Words the sign languages leave unsigned: grammar, carried by order, the face or pointing instead.
FILLER = {
    "a", "an", "the", "is", "are", "am", "was", "were", "be", "to", "of", "do", "does", "did", "for", "and",
    "hai", "hain", "tha", "thi", "the", "ka", "ki", "ke", "ko", "mein", "se", "ne", "to", "bhi", "aur",
}
UNSIGNED = {"in", "at", "on", "into", "with", "about", "or", "it", "there", "by", "from", "if", "any", "their",
            "your", "you", "i", "me", "my", "we", "our", "this", "that", "these", "those", "what", "which",
            "where", "when", "who", "whom", "how", "why", "not", "no", "yes", "please", "can", "will", "would",
            "should", "may", "must", "have", "has", "had", "don", "doesn", "didn", "won", "isn"}

TOKEN = re.compile(r"[\w']+", re.UNICODE)


def base(word: str) -> str:
    """A word's stem, as TextSigning.base does: 'years' is year, 'doing' is do."""
    if len(word) < 4:
        return word
    for suffix, add in (("ies", "y"), ("es", ""), ("s", ""), ("ing", ""), ("ing", "e"), ("ed", ""), ("d", "")):
        if word.endswith(suffix):
            stem = word[: -len(suffix)] + add
            if len(stem) >= 2:
                return stem
    return word


def signed_vocabulary() -> set[str]:
    words = json.loads((ASSETS / "words.json").read_text(encoding="utf-8"))["words"]
    out: set[str] = set()
    for entry in words:
        out.update(w.lower() for w in entry["w"])
    for sign in json.loads((ASSETS / "isl_signs.json").read_text(encoding="utf-8"))["gestures"]:
        if sign.get("word"):
            out.add(sign["word"].lower())
        if sign.get("hi"):
            out.add(sign["hi"])
    return out


def has_sign(word: str, vocab: set[str]) -> bool:
    return word in vocab or base(word) in vocab


def main() -> int:
    questions = json.loads((ASSETS / "triage.json").read_text(encoding="utf-8"))["questions"]
    vocab = signed_vocabulary()
    missing: collections.Counter[str] = collections.Counter()
    gapped: list[tuple[str, str, list[str]]] = []
    for q in questions:
        text = q["text"]["en"]
        gaps = []
        for word in TOKEN.findall(text.lower()):
            # "father's" is signed as father: a possessive keeps only its stem, as TextSigning plans it.
            word = word.split("'")[0]
            if word in FILLER or word in UNSIGNED or has_sign(word, vocab):
                continue
            gaps.append(word)
            missing[word] += 1
        if gaps:
            gapped.append((q["id"], text, gaps))
    total = sum(1 for q in questions for w in TOKEN.findall(q["text"]["en"].lower())
                if w not in FILLER and w not in UNSIGNED)
    gaps = sum(missing.values())
    print(f"{len(questions)} questions, {total} content words, {gaps} without a sign "
          f"({100 * (total - gaps) / max(total, 1):.1f}% covered)")
    print(f"{len(gapped)} of {len(questions)} questions would be partly fingerspelled")
    if missing:
        print("\nmost used words without a sign:")
        for word, n in missing.most_common(25):
            print(f"  {n:3}  {word}")
    TARGETS.parent.mkdir(parents=True, exist_ok=True)
    TARGETS.write_text(
        "# Words the shipped questions use that have no sign: the target list for the next training run or\n"
        "# recording session, most used first. Generated by tools/content/coverage.py.\n"
        + "".join(f"{word}\n" for word, _ in missing.most_common()),
        encoding="utf-8",
    )
    print(f"\nwrote {TARGETS.relative_to(ROOT).as_posix()} ({len(missing)} words)")
    if "--check" in sys.argv and len(gapped) > MAX_GAPPED:
        print(f"too many questions with a gap: {len(gapped)} > {MAX_GAPPED}")
        return 1
    return 0


MAX_GAPPED = 80

if __name__ == "__main__":
    sys.exit(main())
